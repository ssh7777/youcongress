export const sql = `
CREATE TABLE guest_sessions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash TEXT NOT NULL UNIQUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  expires_at TIMESTAMPTZ NOT NULL,
  CONSTRAINT guest_sessions_token_hash_length CHECK (char_length(token_hash) = 64)
);

CREATE INDEX guest_sessions_lookup_idx ON guest_sessions(token_hash, expires_at);
CREATE INDEX guest_sessions_user_id_idx ON guest_sessions(user_id);

ALTER TABLE quotes ADD COLUMN created_by BIGINT REFERENCES users(id) ON DELETE SET NULL;
CREATE INDEX quotes_created_by_idx ON quotes(created_by);
`;
