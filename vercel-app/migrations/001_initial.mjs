export const version = '001_initial';

export const sql = `
CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT,
  display_name TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX users_email_unique ON users (LOWER(email)) WHERE email IS NOT NULL;

CREATE TABLE policy_statements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE,
  title TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT policy_statements_slug_length CHECK (char_length(slug) BETWEEN 1 AND 250),
  CONSTRAINT policy_statements_title_length CHECK (char_length(title) BETWEEN 1 AND 500)
);

CREATE TABLE quotes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  statement_id BIGINT NOT NULL REFERENCES policy_statements(id) ON DELETE CASCADE,
  author_name TEXT,
  content TEXT NOT NULL,
  source_url TEXT NOT NULL,
  source_text TEXT NOT NULL,
  quote_date DATE,
  date_precision TEXT,
  verification_status TEXT NOT NULL DEFAULT 'unverified',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT quotes_source_url_present CHECK (char_length(btrim(source_url)) > 0),
  CONSTRAINT quotes_source_text_present CHECK (char_length(btrim(source_text)) > 0)
);

CREATE INDEX quotes_statement_id_idx ON quotes(statement_id, id DESC);

CREATE TABLE votes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  statement_id BIGINT NOT NULL REFERENCES policy_statements(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  position TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT votes_position_valid CHECK (position IN ('for', 'against', 'abstain')),
  CONSTRAINT votes_statement_user_unique UNIQUE (statement_id, user_id)
);

CREATE INDEX votes_user_id_idx ON votes(user_id);

CREATE TABLE intelligence_posts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE,
  title TEXT NOT NULL,
  summary TEXT NOT NULL DEFAULT '',
  content TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'draft',
  author_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
  published_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT intelligence_posts_status_valid CHECK (status IN ('draft', 'published', 'archived')),
  CONSTRAINT intelligence_posts_slug_length CHECK (char_length(slug) BETWEEN 1 AND 250)
);

CREATE INDEX intelligence_posts_published_idx ON intelligence_posts(published_at DESC, id DESC)
  WHERE status = 'published';

CREATE TABLE reconsiderations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  statement_id BIGINT NOT NULL REFERENCES policy_statements(id) ON DELETE CASCADE,
  requested_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  rationale TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'open',
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT reconsiderations_status_valid CHECK (status IN ('open', 'accepted', 'declined', 'closed'))
);

CREATE INDEX reconsiderations_open_idx ON reconsiderations(created_at DESC, id DESC)
  WHERE status = 'open';
`;
